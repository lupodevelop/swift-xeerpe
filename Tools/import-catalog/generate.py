#!/usr/bin/env python3
"""Turns the JSON written by extract.mjs into Swift preset data.

Usage: generate.py <presets.json> <output dir>
Writes one file per category plus Index.swift.
"""
import json, re, sys, os

HEADER = """// Generated by Tools/import-catalog. Do not edit.
// The colors and layer values derive from the presets of the xeerpe
// TypeScript library by Nicola Centonze (MIT License).
"""
CATEGORIES = ["metals", "gems", "food", "nature", "sky", "space", "neon", "pastel", "neutral", "luxury", "textures", "moods", "motion"]
DIRECTIONS = {"to top": 0, "to right": 90, "to bottom": 180, "to left": 270,
              "to top right": 45, "to bottom right": 135, "to bottom left": 225, "to top left": 315}


def rgba(s):
    if s == "transparent":
        return 0
    h = s.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) == 6:
        h += "ff"
    return int(h, 16)


def pct(s, default=0.0):
    if s is None:
        return default
    m = re.fullmatch(r"\s*(-?[\d.]+)(%|px)?\s*", str(s))
    if not m:
        return default
    return float(m.group(1)) / 100 if m.group(2) == "%" else (0.0 if m.group(2) == "px" else float(m.group(1)))


def num(s, default):
    m = re.search(r"-?[\d.]+", str(s)) if s is not None else None
    return float(m.group(0)) if m else default


def pos(s):
    a, b = str(s).split()
    return pct(a), pct(b)


def hexs(v):
    return "0x%08x" % v


def f(v):
    return repr(round(float(v), 4))


def solid_neighbors(stops):
    """CSS fades to transparent in premultiplied space; keep the neighbor's RGB."""
    out = [list(s) for s in stops]
    for i, (c, _) in enumerate(out):
        if c & 0xff == 0:
            for j in sorted(range(len(out)), key=lambda k: abs(k - i)):
                if out[j][0] & 0xff:
                    out[i][0] = out[j][0] & 0xffffff00
                    break
    return out


def convert(calls):
    fills, overlays, post, motion, base = [], [], [], [], None
    for c in calls:
        m, a = c["method"], (c["args"][0] if c["args"] else {}) or {}
        if m == "meshGradient":
            for l in a.get("layers", []):
                x, y = pos(l["position"])
                fr, to = rgba(l["from"]), rgba(l["to"])
                if to & 0xff == 0:
                    to = fr & 0xffffff00
                w = h = None
                if "size" in l:
                    w, h = pos(l["size"])
                fa = pct(l.get("colorFromPosition"), 0.0)
                ta = pct(l.get("colorToPosition"), 1.0)
                fills.append(f".blob(x: {f(x)}, y: {f(y)}, from: {hexs(fr)}, to: {hexs(to)}, fromAt: {f(fa)}, toAt: {f(max(ta, fa))}, "
                             f"w: {f(w) if w is not None else 'nil'}, h: {f(h) if h is not None else 'nil'})")
            bg = a.get("background", "transparent")
            if bg != "transparent":
                base = rgba(bg)
        elif m == "linearGradient":
            css = num(a["angle"], 180) if "angle" in a else DIRECTIONS.get(a.get("direction", "to bottom"), 180)
            span = max(num(a["backgroundSize"], 100) / 100, 1) if "backgroundSize" in a else 1
            stops = solid_neighbors([(rgba(s["color"]) if isinstance(s, dict) else rgba(s), pct(s.get("position"), i / max(len(a["colors"]) - 1, 1)) if isinstance(s, dict) else i / max(len(a["colors"]) - 1, 1)) for i, s in enumerate(a["colors"])])
            body = ", ".join(f"XeerpeStop({hexs(c)}, {f(p)})" for c, p in stops)
            fills.append(f".stops([{body}], css: {f(css)}" + (f", span: {f(span)}" if span != 1 else "") + ")")
        elif m == "vignette":
            overlays.append(f".vignette(color: {hexs(rgba(a.get('color', '#000000')))}, intensity: {f(a.get('intensity', 0.2))}, spread: {f(a.get('spread', 0.2))})")
        elif m == "grid":
            overlays.append(f".grid(color: {hexs(rgba(a.get('color', '#ffffff')))}, size: {f(num(a.get('size'), 24))}, line: {f(num(a.get('strokeWidth'), 1))}, opacity: {f(a.get('opacity', 0.2))})")
        elif m == "dots":
            overlays.append(f".dots(color: {hexs(rgba(a.get('color', '#ffffff')))}, size: {f(num(a.get('size'), 16))}, radius: {f(num(a.get('strokeWidth'), 2) / 2 if 'strokeWidth' in a else 1.5)}, opacity: {f(a.get('opacity', 0.2))})")
        elif m == "stars":
            overlays.append(f".stars(color: {hexs(rgba(a.get('color', '#ffffff')))}, count: {int(a.get('count', 40))}, seed: {int(a.get('seed', 1))}, radius: {f(num(a.get('strokeWidth'), 1.5) / 2)}, opacity: {f(a.get('opacity', 1))})")
        elif m == "rays":
            x, y = pos(a.get("position", "50% 50%"))
            overlays.append(f".rays(color: {hexs(rgba(a.get('color', '#ffffff')))}, opacity: {f(a.get('opacity', 0.1))}, count: {int(a.get('count', 12))}, x: {f(x)}, y: {f(y)}, css: {f(num(a.get('angle'), 0))})")
        elif m == "grain":
            post.append(f".grain({f(a.get('intensity', 1))})")
        elif m == "noise":
            post.append(f".noise(opacity: {f(a.get('opacity', 0.1))}, scale: {f(a.get('scale', 0.5))})")
        elif m in ("breathe", "aurora", "drift", "shimmer"):
            motion.append(f".{m}(period: {f(num(a.get('duration'), 6))})")
        else:
            raise SystemExit(f"unknown method {m}")
    layers = fills + ([f".base({hexs(base)})"] if base is not None else []) + overlays + post
    return layers, motion


def main():
    src, out = sys.argv[1:3]
    data = json.load(open(src))
    os.makedirs(out, exist_ok=True)
    seen = set()
    total = 0
    for cat in CATEGORIES:
        lines = [HEADER, f"extension XeerpeCatalog {{\n    static var {cat}Presets: [XeerpePreset] {{\n        ["]
        for pid, calls in data[cat].items():
            ident = pid if pid not in seen else f"{cat}-{pid}"
            seen.add(ident)
            layers, motion = convert(calls)
            ls = ",\n                ".join(layers)
            ms = f", motion: [{', '.join(motion)}]" if motion else ""
            lines.append(f'            XeerpePreset("{ident}", .{cat}, layers: [\n                {ls},\n            ]{ms}),')
            total += 1
        lines.append("        ]\n    }\n}\n")
        open(os.path.join(out, f"Catalog{cat.capitalize()}.swift"), "w").write("\n".join(lines))
    idx = [HEADER, "extension XeerpeCatalog {", "    static var generated: [XeerpePreset] {", "        " + " + ".join(f"{c}Presets" for c in CATEGORIES), "    }", "}", ""]
    open(os.path.join(out, "CatalogIndex.swift"), "w").write("\n".join(idx))
    print(f"{total} presets")


main()
